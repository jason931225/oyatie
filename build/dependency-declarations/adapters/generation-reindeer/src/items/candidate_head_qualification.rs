// Fail-closed qualification of one immutable candidate with the pinned Reindeer provider.

use dependency_declarations_generation::GenerationPort;
use std::fmt;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

/// Repository identity bound into every admitted artifact.
pub const QUALIFICATION_REPOSITORY: &str = "github.com/oyatie/oyatie";

/// Exact upstream provider revision admitted by this adapter.
pub const PINNED_REINDEER_COMMIT: &str =
    "bb681570d2bc47d1446080c12b8681a50a95f628";

/// Exact upstream provider tree admitted by this adapter.
pub const PINNED_REINDEER_TREE: &str =
    "153f32a846b5e1f460e61fff1cecbbf5177c8c90";

/// Toolchain used to compile the pinned upstream provider.
pub const PINNED_REINDEER_BUILD_TOOLCHAIN: &str = "nightly-2026-05-22";

/// Toolchain used by Cargo while reading the candidate dependency graph.
pub const PINNED_CANDIDATE_TOOLCHAIN: &str = "1.98.0";

const PINNED_CANDIDATE_TOOLCHAIN_FILE: &[u8] = b"[toolchain]\nchannel = \"1.98.0\"\ncomponents = [\"rustfmt\", \"clippy\"]\nprofile = \"minimal\"\n";

/// All paths and immutable identities required for one qualification attempt.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct CandidateHeadQualificationRequest {
    pub provider_executable: PathBuf,
    pub provider_commit: String,
    pub provider_tree: String,
    pub candidate_root: PathBuf,
    pub candidate_commit: String,
    pub candidate_tree: String,
    pub cargo_executable: PathBuf,
    pub rustc_executable: PathBuf,
    pub cargo_home: PathBuf,
    pub first_target_dir: PathBuf,
    pub second_target_dir: PathBuf,
}

/// Byte-identical output from two independent target directories.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct CandidateHeadQualificationArtifact {
    candidate_commit: String,
    candidate_tree: String,
    generated_buck: Vec<u8>,
}

impl CandidateHeadQualificationArtifact {
    /// SCM-neutral repository identity for this artifact.
    #[must_use]
    pub fn repository(&self) -> &'static str {
        QUALIFICATION_REPOSITORY
    }

    /// Immutable candidate commit supplied by the caller.
    #[must_use]
    pub fn candidate_commit(&self) -> &str {
        &self.candidate_commit
    }

    /// Immutable candidate tree supplied by the caller.
    #[must_use]
    pub fn candidate_tree(&self) -> &str {
        &self.candidate_tree
    }

    /// Exact Reindeer revision used to produce the output.
    #[must_use]
    pub fn provider_commit(&self) -> &'static str {
        PINNED_REINDEER_COMMIT
    }

    /// Exact Reindeer tree used to produce the output.
    #[must_use]
    pub fn provider_tree(&self) -> &'static str {
        PINNED_REINDEER_TREE
    }

    /// Toolchain used to compile the provider executable.
    #[must_use]
    pub fn provider_build_toolchain(&self) -> &'static str {
        PINNED_REINDEER_BUILD_TOOLCHAIN
    }

    /// Toolchain used by Cargo to inspect the candidate.
    #[must_use]
    pub fn candidate_toolchain(&self) -> &'static str {
        PINNED_CANDIDATE_TOOLCHAIN
    }

    /// Reproducible, nonempty `reindeer buckify --stdout` bytes.
    #[must_use]
    pub fn generated_buck(&self) -> &[u8] {
        &self.generated_buck
    }

    /// Consume the artifact and return its generated bytes.
    #[must_use]
    pub fn into_generated_buck(self) -> Vec<u8> {
        self.generated_buck
    }
}

/// Which independent provider execution failed.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QualificationRun {
    First,
    Second,
}

/// A candidate file that the provider is forbidden to change.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ProtectedCandidateInput {
    CargoLock,
    ThirdPartyBuck,
}

impl ProtectedCandidateInput {
    fn relative_path(self) -> &'static str {
        match self {
            Self::CargoLock => "Cargo.lock",
            Self::ThirdPartyBuck => "third-party/BUCK",
        }
    }
}

/// Input path named by a qualification request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QualificationPath {
    ProviderExecutable,
    CandidateRoot,
    CandidateConfig,
    CandidateCargoLock,
    CandidateThirdPartyBuck,
    CandidateToolchain,
    CargoExecutable,
    RustcExecutable,
    CargoHome,
    FirstTargetDirectory,
    SecondTargetDirectory,
}

/// Why a request path was refused before execution.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum PathRefusal {
    NotAbsolute,
    Missing,
    NotAFile,
    NotADirectory,
    NotExecutable,
    AliasesAnotherExecutionDirectory,
    InsideCandidateRoot,
    DoesNotMatchProviderCargoHome,
}

/// Immutable identity field named by a qualification request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RevisionField {
    ProviderCommit,
    ProviderTree,
    CandidateCommit,
    CandidateTree,
}

/// Typed, fail-closed refusal from candidate qualification.
#[derive(Debug, Eq, PartialEq)]
pub enum CandidateHeadQualificationFailure {
    InvalidPath {
        field: QualificationPath,
        path: PathBuf,
        reason: PathRefusal,
    },
    InvalidRevision {
        field: RevisionField,
    },
    ProviderIdentityMismatch {
        field: RevisionField,
    },
    CandidateToolchainMismatch,
    ProtectedInputRead {
        input: ProtectedCandidateInput,
        run: Option<QualificationRun>,
        kind: io::ErrorKind,
    },
    ProviderSpawn {
        run: QualificationRun,
        kind: io::ErrorKind,
    },
    ProtectedInputChanged {
        input: ProtectedCandidateInput,
        run: QualificationRun,
    },
    ProviderExit {
        run: QualificationRun,
        code: Option<i32>,
        stdout_bytes: usize,
        stderr: Vec<u8>,
    },
    ProviderStderr {
        run: QualificationRun,
        stderr: Vec<u8>,
    },
    EmptyOutput {
        run: QualificationRun,
    },
    NondeterministicOutput {
        first_bytes: usize,
        second_bytes: usize,
        first_difference: usize,
    },
}

impl fmt::Display for CandidateHeadQualificationFailure {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidPath {
                field,
                path,
                reason,
            } => write!(
                formatter,
                "qualification path {field:?} at {} was refused: {reason:?}",
                path.display()
            ),
            Self::InvalidRevision { field } => {
                write!(formatter, "qualification revision {field:?} is not a lowercase 40-byte object id")
            }
            Self::ProviderIdentityMismatch { field } => {
                write!(formatter, "qualification provider identity {field:?} does not match the admitted pin")
            }
            Self::CandidateToolchainMismatch => write!(
                formatter,
                "candidate rust-toolchain.toml does not select the admitted 1.98.0 toolchain"
            ),
            Self::ProtectedInputRead { input, run, kind } => write!(
                formatter,
                "protected candidate input {input:?} could not be read at {run:?}: {kind:?}"
            ),
            Self::ProviderSpawn { run, kind } => {
                write!(formatter, "{run:?} Reindeer execution could not start: {kind:?}")
            }
            Self::ProtectedInputChanged { input, run } => write!(
                formatter,
                "{run:?} Reindeer execution changed protected candidate input {input:?}"
            ),
            Self::ProviderExit {
                run,
                code,
                stdout_bytes,
                stderr,
            } => write!(
                formatter,
                "{run:?} Reindeer execution failed with code {code:?}, {stdout_bytes} withheld stdout bytes, and {} diagnostic bytes",
                stderr.len()
            ),
            Self::ProviderStderr { run, stderr } => write!(
                formatter,
                "{run:?} Reindeer execution succeeded but emitted {} diagnostic bytes",
                stderr.len()
            ),
            Self::EmptyOutput { run } => {
                write!(formatter, "{run:?} Reindeer execution emitted an empty artifact")
            }
            Self::NondeterministicOutput {
                first_bytes,
                second_bytes,
                first_difference,
            } => write!(
                formatter,
                "Reindeer executions differed at byte {first_difference} ({first_bytes} versus {second_bytes} bytes)"
            ),
        }
    }
}

impl std::error::Error for CandidateHeadQualificationFailure {}

/// Stateless implementation of the exact-provider qualification protocol.
#[derive(Clone, Copy, Debug, Default)]
pub struct ReindeerCandidateHeadQualifier;

impl
    GenerationPort<
        CandidateHeadQualificationRequest,
        CandidateHeadQualificationArtifact,
        CandidateHeadQualificationFailure,
    > for ReindeerCandidateHeadQualifier
{
    fn generate(
        &self,
        request: &CandidateHeadQualificationRequest,
    ) -> Result<CandidateHeadQualificationArtifact, CandidateHeadQualificationFailure> {
        qualify_candidate_head(request)
    }
}

/// Run the pinned provider twice and admit only a reproducible, non-mutating result.
pub fn qualify_candidate_head(
    request: &CandidateHeadQualificationRequest,
) -> Result<CandidateHeadQualificationArtifact, CandidateHeadQualificationFailure> {
    let validated = ValidatedRequest::new(request)?;
    let protected = ProtectedSnapshot::read(&validated.candidate_root)?;

    let first = run_once(&validated, QualificationRun::First, &protected)?;
    let second = run_once(&validated, QualificationRun::Second, &protected)?;
    if first.stdout != second.stdout {
        return Err(CandidateHeadQualificationFailure::NondeterministicOutput {
            first_bytes: first.stdout.len(),
            second_bytes: second.stdout.len(),
            first_difference: first_difference(&first.stdout, &second.stdout),
        });
    }

    Ok(CandidateHeadQualificationArtifact {
        candidate_commit: request.candidate_commit.clone(),
        candidate_tree: request.candidate_tree.clone(),
        generated_buck: first.stdout,
    })
}

struct ValidatedRequest {
    provider_executable: PathBuf,
    candidate_root: PathBuf,
    cargo_executable: PathBuf,
    rustc_executable: PathBuf,
    cargo_home: PathBuf,
    first_target_dir: PathBuf,
    second_target_dir: PathBuf,
}

impl ValidatedRequest {
    fn new(
        request: &CandidateHeadQualificationRequest,
    ) -> Result<Self, CandidateHeadQualificationFailure> {
        validate_revision(&request.provider_commit, RevisionField::ProviderCommit)?;
        validate_revision(&request.provider_tree, RevisionField::ProviderTree)?;
        validate_revision(&request.candidate_commit, RevisionField::CandidateCommit)?;
        validate_revision(&request.candidate_tree, RevisionField::CandidateTree)?;
        if request.provider_commit != PINNED_REINDEER_COMMIT {
            return Err(CandidateHeadQualificationFailure::ProviderIdentityMismatch {
                field: RevisionField::ProviderCommit,
            });
        }
        if request.provider_tree != PINNED_REINDEER_TREE {
            return Err(CandidateHeadQualificationFailure::ProviderIdentityMismatch {
                field: RevisionField::ProviderTree,
            });
        }

        let provider_executable = validate_file(
            &request.provider_executable,
            QualificationPath::ProviderExecutable,
            true,
        )?;
        let candidate_root = validate_directory(
            &request.candidate_root,
            QualificationPath::CandidateRoot,
        )?;
        validate_file(
            &candidate_root.join("reindeer.toml"),
            QualificationPath::CandidateConfig,
            false,
        )?;
        validate_file(
            &candidate_root.join("Cargo.lock"),
            QualificationPath::CandidateCargoLock,
            false,
        )?;
        validate_file(
            &candidate_root.join("third-party/BUCK"),
            QualificationPath::CandidateThirdPartyBuck,
            false,
        )?;
        let candidate_toolchain = validate_file(
            &candidate_root.join("rust-toolchain.toml"),
            QualificationPath::CandidateToolchain,
            false,
        )?;
        if fs::read(candidate_toolchain).ok().as_deref()
            != Some(PINNED_CANDIDATE_TOOLCHAIN_FILE)
        {
            return Err(CandidateHeadQualificationFailure::CandidateToolchainMismatch);
        }

        let cargo_executable = validate_file(
            &request.cargo_executable,
            QualificationPath::CargoExecutable,
            true,
        )?;
        let rustc_executable = validate_file(
            &request.rustc_executable,
            QualificationPath::RustcExecutable,
            true,
        )?;
        let cargo_home = validate_directory(&request.cargo_home, QualificationPath::CargoHome)?;
        let provider_cargo_home = validate_directory(
            &candidate_root.join("third-party/.cargo"),
            QualificationPath::CargoHome,
        )?;
        if cargo_home != provider_cargo_home {
            return Err(CandidateHeadQualificationFailure::InvalidPath {
                field: QualificationPath::CargoHome,
                path: cargo_home,
                reason: PathRefusal::DoesNotMatchProviderCargoHome,
            });
        }

        let first_target_dir = validate_directory(
            &request.first_target_dir,
            QualificationPath::FirstTargetDirectory,
        )?;
        let second_target_dir = validate_directory(
            &request.second_target_dir,
            QualificationPath::SecondTargetDirectory,
        )?;
        if first_target_dir == second_target_dir {
            return Err(CandidateHeadQualificationFailure::InvalidPath {
                field: QualificationPath::SecondTargetDirectory,
                path: second_target_dir,
                reason: PathRefusal::AliasesAnotherExecutionDirectory,
            });
        }
        for (field, target) in [
            (QualificationPath::FirstTargetDirectory, &first_target_dir),
            (QualificationPath::SecondTargetDirectory, &second_target_dir),
        ] {
            if target.starts_with(&candidate_root) {
                return Err(CandidateHeadQualificationFailure::InvalidPath {
                    field,
                    path: target.clone(),
                    reason: PathRefusal::InsideCandidateRoot,
                });
            }
        }

        Ok(Self {
            provider_executable,
            candidate_root,
            cargo_executable,
            rustc_executable,
            cargo_home,
            first_target_dir,
            second_target_dir,
        })
    }
}

fn validate_revision(
    value: &str,
    field: RevisionField,
) -> Result<(), CandidateHeadQualificationFailure> {
    if value.len() == 40
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
    {
        Ok(())
    } else {
        Err(CandidateHeadQualificationFailure::InvalidRevision { field })
    }
}

fn validate_file(
    path: &Path,
    field: QualificationPath,
    executable: bool,
) -> Result<PathBuf, CandidateHeadQualificationFailure> {
    let canonical = canonical_path(path, field)?;
    if !canonical.is_file() {
        return Err(CandidateHeadQualificationFailure::InvalidPath {
            field,
            path: canonical,
            reason: PathRefusal::NotAFile,
        });
    }
    #[cfg(unix)]
    if executable {
        use std::os::unix::fs::PermissionsExt;
        let mode = fs::metadata(&canonical)
            .map_err(|_| CandidateHeadQualificationFailure::InvalidPath {
                field,
                path: canonical.clone(),
                reason: PathRefusal::Missing,
            })?
            .permissions()
            .mode();
        if mode & 0o111 == 0 {
            return Err(CandidateHeadQualificationFailure::InvalidPath {
                field,
                path: canonical,
                reason: PathRefusal::NotExecutable,
            });
        }
    }
    #[cfg(not(unix))]
    let _ = executable;
    Ok(canonical)
}

fn validate_directory(
    path: &Path,
    field: QualificationPath,
) -> Result<PathBuf, CandidateHeadQualificationFailure> {
    let canonical = canonical_path(path, field)?;
    if canonical.is_dir() {
        Ok(canonical)
    } else {
        Err(CandidateHeadQualificationFailure::InvalidPath {
            field,
            path: canonical,
            reason: PathRefusal::NotADirectory,
        })
    }
}

fn canonical_path(
    path: &Path,
    field: QualificationPath,
) -> Result<PathBuf, CandidateHeadQualificationFailure> {
    if !path.is_absolute() {
        return Err(CandidateHeadQualificationFailure::InvalidPath {
            field,
            path: path.to_path_buf(),
            reason: PathRefusal::NotAbsolute,
        });
    }
    fs::canonicalize(path).map_err(|_| CandidateHeadQualificationFailure::InvalidPath {
        field,
        path: path.to_path_buf(),
        reason: PathRefusal::Missing,
    })
}

struct ProtectedSnapshot {
    cargo_lock: Vec<u8>,
    third_party_buck: Vec<u8>,
}

impl ProtectedSnapshot {
    fn read(candidate_root: &Path) -> Result<Self, CandidateHeadQualificationFailure> {
        Ok(Self {
            cargo_lock: read_protected(
                candidate_root,
                ProtectedCandidateInput::CargoLock,
                None,
            )?,
            third_party_buck: read_protected(
                candidate_root,
                ProtectedCandidateInput::ThirdPartyBuck,
                None,
            )?,
        })
    }

    fn require_unchanged(
        &self,
        candidate_root: &Path,
        run: QualificationRun,
    ) -> Result<(), CandidateHeadQualificationFailure> {
        for (input, before) in [
            (ProtectedCandidateInput::CargoLock, self.cargo_lock.as_slice()),
            (
                ProtectedCandidateInput::ThirdPartyBuck,
                self.third_party_buck.as_slice(),
            ),
        ] {
            let after = read_protected(candidate_root, input, Some(run))?;
            if before != after {
                return Err(CandidateHeadQualificationFailure::ProtectedInputChanged {
                    input,
                    run,
                });
            }
        }
        Ok(())
    }
}

fn read_protected(
    candidate_root: &Path,
    input: ProtectedCandidateInput,
    run: Option<QualificationRun>,
) -> Result<Vec<u8>, CandidateHeadQualificationFailure> {
    fs::read(candidate_root.join(input.relative_path())).map_err(|error| {
        CandidateHeadQualificationFailure::ProtectedInputRead {
            input,
            run,
            kind: error.kind(),
        }
    })
}

fn run_once(
    request: &ValidatedRequest,
    run: QualificationRun,
    protected: &ProtectedSnapshot,
) -> Result<Output, CandidateHeadQualificationFailure> {
    let target_dir = match run {
        QualificationRun::First => &request.first_target_dir,
        QualificationRun::Second => &request.second_target_dir,
    };
    let config = request.candidate_root.join("reindeer.toml");
    let mut command = Command::new(&request.provider_executable);
    command
        .arg("-c")
        .arg(config)
        .arg("--cargo-path")
        .arg(&request.cargo_executable)
        .arg("--rustc-path")
        .arg(&request.rustc_executable)
        .arg("--cargo-options=--locked")
        .arg("buckify")
        .arg("--stdout")
        .current_dir(&request.candidate_root)
        .env_clear()
        .env("CARGO_HOME", &request.cargo_home)
        .env("CARGO_NET_OFFLINE", "true")
        .env("CARGO_TARGET_DIR", target_dir)
        .env("LANG", "C")
        .env("LC_ALL", "C")
        .env("RUSTUP_TOOLCHAIN", PINNED_CANDIDATE_TOOLCHAIN)
        .env("TZ", "UTC")
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());

    let output = command.output();
    protected.require_unchanged(&request.candidate_root, run)?;
    let output = output.map_err(|error| CandidateHeadQualificationFailure::ProviderSpawn {
        run,
        kind: error.kind(),
    })?;
    if !output.status.success() {
        return Err(CandidateHeadQualificationFailure::ProviderExit {
            run,
            code: output.status.code(),
            stdout_bytes: output.stdout.len(),
            stderr: output.stderr,
        });
    }
    if !output.stderr.is_empty() {
        return Err(CandidateHeadQualificationFailure::ProviderStderr {
            run,
            stderr: output.stderr,
        });
    }
    if output.stdout.is_empty() {
        return Err(CandidateHeadQualificationFailure::EmptyOutput { run });
    }
    Ok(output)
}

fn first_difference(first: &[u8], second: &[u8]) -> usize {
    first
        .iter()
        .zip(second)
        .position(|(left, right)| left != right)
        .unwrap_or_else(|| first.len().min(second.len()))
}
