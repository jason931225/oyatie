use std::time::{Duration, Instant};

/// Longest provider execution admitted by the native runner.
pub const MAX_QUALIFICATION_RUNTIME: Duration = Duration::from_secs(40 * 60);
/// Largest generated artifact admitted by the native runner.
pub const MAX_GENERATED_OUTPUT_BYTES: usize = 64 * 1024 * 1024;
/// Largest provider diagnostic admitted by the native runner.
pub const MAX_DIAGNOSTIC_OUTPUT_BYTES: usize = 1024 * 1024;
/// Largest number of entries admitted in one compared tree.
pub const MAX_TREE_ENTRIES: u64 = 1_000_000;
/// Largest individual file admitted in one compared tree.
pub const MAX_TREE_FILE_BYTES: u64 = 128 * 1024 * 1024;
/// Largest aggregate regular-file content admitted in one compared tree.
pub const MAX_TREE_TOTAL_BYTES: u64 = 512 * 1024 * 1024;
/// Deepest directory nesting admitted in one compared tree.
pub const MAX_TREE_DEPTH: u64 = 128;

/// Caller-supplied paths used by one two-root qualification attempt.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct CandidateHeadQualificationRequest {
    pub provider_executable: PathBuf,
    pub cargo_executable: PathBuf,
    pub rustc_executable: PathBuf,
    pub first_candidate_root: PathBuf,
    pub second_candidate_root: PathBuf,
    pub first_target_dir: PathBuf,
    pub second_target_dir: PathBuf,
}
/// Byte-identical output from two isolated candidate roots.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct CandidateHeadQualificationArtifact {
    generated_buck: Vec<u8>,
}

impl CandidateHeadQualificationArtifact {
    /// Reproducible, nonempty generated Buck bytes.
    #[must_use]
    pub fn generated_buck(&self) -> &[u8] {
        &self.generated_buck
    }

    /// Consume the artifact and return its generated bytes.
    #[must_use]
    pub fn into_generated_buck(self) -> Vec<u8> {
        self.generated_buck
    }
}

/// Which provider execution is named by a refusal.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QualificationRun {
    First,
    Second,
}

/// Which candidate root is named by a refusal.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CandidateRoot {
    First,
    Second,
}

impl From<QualificationRun> for CandidateRoot {
    fn from(run: QualificationRun) -> Self {
        match run {
            QualificationRun::First => Self::First,
            QualificationRun::Second => Self::Second,
        }
    }
}

/// Which in-root byte tree is being compared or protected.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CandidateTreeScope {
    Semantic,
    CargoSeed,
}

/// Input path named by a qualification request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QualificationPath {
    ProviderExecutable,
    CargoExecutable,
    RustcExecutable,
    FirstCandidateRoot,
    SecondCandidateRoot,
    FirstTargetDirectory,
    SecondTargetDirectory,
}

/// Why a request path was refused before execution.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum PathRefusal {
    NotAbsolute,
    Missing,
    NotAFile,
    NotADirectory,
    NotExecutable,
    Symlink,
    NonCanonical,
    AlreadyExists,
    ParentMissing,
    InvalidName,
    OverlapsAnotherInput,
    AliasesAnotherExecutable,
}

/// Native resource bound that was invalid or exceeded.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QualificationLimit {
    Runtime,
    StdoutBytes,
    StderrBytes,
    TreeEntries,
    TreeFileBytes,
    TreeTotalBytes,
    TreeDepth,
}

/// Provider output stream named by a refusal.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QualificationStream {
    Stdout,
    Stderr,
}

/// External executable protected by the runner.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QualificationTool {
    Provider,
    Cargo,
    Rustc,
}

/// Candidate filesystem entry the runner cannot safely qualify.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum UnsupportedCandidateEntryKind {
    Symlink,
    Special,
    NonUtf8Name,
    ScmMetadata,
    AliasesExternalTool,
}

/// Native qualification resource limits.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct QualificationLimits {
    pub runtime: Duration,
    pub stdout_bytes: usize,
    pub stderr_bytes: usize,
    pub tree_entries: u64,
    pub tree_file_bytes: u64,
    pub tree_total_bytes: u64,
    pub tree_depth: u64,
}

impl Default for QualificationLimits {
    fn default() -> Self {
        Self {
            runtime: MAX_QUALIFICATION_RUNTIME,
            stdout_bytes: MAX_GENERATED_OUTPUT_BYTES,
            stderr_bytes: MAX_DIAGNOSTIC_OUTPUT_BYTES,
            tree_entries: MAX_TREE_ENTRIES,
            tree_file_bytes: MAX_TREE_FILE_BYTES,
            tree_total_bytes: MAX_TREE_TOTAL_BYTES,
            tree_depth: MAX_TREE_DEPTH,
        }
    }
}

/// Implementation of the two-root qualification protocol.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct ReindeerCandidateHeadQualifier {
    limits: QualificationLimits,
}

impl ReindeerCandidateHeadQualifier {
    /// Construct a qualifier with stricter test or operator limits.
    #[must_use]
    pub fn with_limits(limits: QualificationLimits) -> Self {
        Self { limits }
    }
}

impl
    GenerationPort<
        CandidateHeadQualificationRequest,
        CandidateHeadQualificationArtifact,
        CandidateHeadQualificationFailure,
    > for ReindeerCandidateHeadQualifier
{
    fn generate(
        &self,
        request: &CandidateHeadQualificationRequest,
    ) -> Result<CandidateHeadQualificationArtifact, CandidateHeadQualificationFailure> {
        qualify_candidate_head_with_limits(request, self.limits)
    }
}

/// Qualify a candidate with the native production bounds.
pub fn qualify_candidate_head(
    request: &CandidateHeadQualificationRequest,
) -> Result<CandidateHeadQualificationArtifact, CandidateHeadQualificationFailure> {
    qualify_candidate_head_with_limits(request, QualificationLimits::default())
}

fn validate_limits(limits: QualificationLimits) -> Result<(), CandidateHeadQualificationFailure> {
    validate_limit(
        QualificationLimit::Runtime,
        limits.runtime.as_nanos(),
        MAX_QUALIFICATION_RUNTIME.as_nanos(),
    )?;
    validate_limit(
        QualificationLimit::StdoutBytes,
        limits.stdout_bytes as u128,
        MAX_GENERATED_OUTPUT_BYTES as u128,
    )?;
    validate_limit(
        QualificationLimit::StderrBytes,
        limits.stderr_bytes as u128,
        MAX_DIAGNOSTIC_OUTPUT_BYTES as u128,
    )?;
    validate_limit(
        QualificationLimit::TreeEntries,
        u128::from(limits.tree_entries),
        u128::from(MAX_TREE_ENTRIES),
    )?;
    validate_limit(
        QualificationLimit::TreeFileBytes,
        u128::from(limits.tree_file_bytes),
        u128::from(MAX_TREE_FILE_BYTES),
    )?;
    validate_limit(
        QualificationLimit::TreeTotalBytes,
        u128::from(limits.tree_total_bytes),
        u128::from(MAX_TREE_TOTAL_BYTES),
    )?;
    validate_limit(
        QualificationLimit::TreeDepth,
        u128::from(limits.tree_depth),
        u128::from(MAX_TREE_DEPTH),
    )
}

fn validate_limit(
    limit: QualificationLimit,
    value: u128,
    maximum: u128,
) -> Result<(), CandidateHeadQualificationFailure> {
    if value == 0 || value > maximum {
        Err(CandidateHeadQualificationFailure::InvalidLimit {
            limit,
            value,
            maximum,
        })
    } else {
        Ok(())
    }
}

fn invalid_path(
    field: QualificationPath,
    path: &Path,
    reason: PathRefusal,
) -> CandidateHeadQualificationFailure {
    CandidateHeadQualificationFailure::InvalidPath {
        field,
        path: path.to_path_buf(),
        reason,
    }
}

fn invalid_path_from_io(
    field: QualificationPath,
    path: &Path,
    error: io::Error,
) -> CandidateHeadQualificationFailure {
    let reason = if error.kind() == io::ErrorKind::NotFound {
        PathRefusal::Missing
    } else {
        PathRefusal::NonCanonical
    };
    invalid_path(field, path, reason)
}
