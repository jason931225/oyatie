use dependency_declarations_generation_reindeer::{
    CandidateHeadQualificationFailure, CandidateHeadQualificationRequest, QualificationRun,
    qualify_candidate_head,
};
use std::env;
use std::fs;
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::process::ExitCode;
use std::time::{SystemTime, UNIX_EPOCH};

const TOOLCHAIN_FILE: &[u8] = b"[toolchain]\nchannel = \"1.98.0\"\ncomponents = [\"rustfmt\", \"clippy\"]\nprofile = \"minimal\"\n";
const REAL_PROVIDER_EXPECTED_BUCK: &[u8] = b"# @generated by \x60reindeer buckify\x60\n\nload(\"@prelude//rust:cargo_buildscript.bzl\", \"buildscript_run\")\nload(\"@prelude//rust:cargo_package.bzl\", \"cargo\")\n\nalias(\n    name = \"qualification-leaf\",\n    actual = \":qualification-leaf-0.1\",\n    visibility = [\"PUBLIC\"],\n)\n\ncargo.rust_library(\n    name = \"qualification-leaf-0.1\",\n    srcs = [\"qualification-leaf/src/lib.rs\"],\n    crate = \"qualification_leaf\",\n    crate_root = \"qualification-leaf/src/lib.rs\",\n    edition = \"2024\",\n    visibility = [],\n)\n";

fn main() -> ExitCode {
    match run() {
        Ok(Success::Candidate(bytes)) => match io::stdout().write_all(&bytes) {
            Ok(()) => ExitCode::SUCCESS,
            Err(error) => {
                eprintln!("Reindeer candidate qualification output failed: {error}");
                ExitCode::from(1)
            }
        },
        Ok(Success::RealProviderFixture(message)) => {
            println!("{message}");
            ExitCode::SUCCESS
        }
        Err(message) => {
            eprintln!("Reindeer candidate qualification refused: {message}");
            ExitCode::from(1)
        }
    }
}

enum Success {
    Candidate(Vec<u8>),
    RealProviderFixture(String),
}

fn run() -> Result<Success, String> {
    let mut args = env::args_os().skip(1);
    let mode = args.next().ok_or_else(|| {
        "exactly one mode is required: real-provider-fixture or candidate".to_owned()
    })?;
    if args.next().is_some() {
        return Err("exactly one mode is required: real-provider-fixture or candidate".to_owned());
    }
    match mode.to_str() {
        Some("real-provider-fixture") => qualify_real_provider_fixture(),
        Some("candidate") => qualify_candidate(),
        _ => Err("mode must be real-provider-fixture or candidate".to_owned()),
    }
}

fn qualify_candidate() -> Result<Success, String> {
    let request = CandidateHeadQualificationRequest {
        provider_executable: required_path("REINDEER_QUALIFICATION_EXECUTABLE")?,
        cargo_executable: required_path("REINDEER_QUALIFICATION_CARGO")?,
        rustc_executable: required_path("REINDEER_QUALIFICATION_RUSTC")?,
        first_candidate_root: required_path("REINDEER_QUALIFICATION_FIRST_CANDIDATE_ROOT")?,
        second_candidate_root: required_path("REINDEER_QUALIFICATION_SECOND_CANDIDATE_ROOT")?,
        first_target_dir: required_path("REINDEER_QUALIFICATION_FIRST_TARGET_DIR")?,
        second_target_dir: required_path("REINDEER_QUALIFICATION_SECOND_TARGET_DIR")?,
    };
    let artifact = qualify_candidate_head(&request).map_err(render_failure)?;
    Ok(Success::Candidate(artifact.into_generated_buck()))
}

fn qualify_real_provider_fixture() -> Result<Success, String> {
    let provider = required_path("REINDEER_QUALIFICATION_EXECUTABLE")?;
    let cargo = required_path("REINDEER_QUALIFICATION_CARGO")?;
    let rustc = required_path("REINDEER_QUALIFICATION_RUSTC")?;

    let success = RealProviderFixture::new(provider.clone(), cargo.clone(), rustc.clone(), false)?;
    qualify_candidate_head(&success.request()).map_err(render_failure)?;

    let unused_fixup = RealProviderFixture::new(provider, cargo, rustc, true)?;
    match qualify_candidate_head(&unused_fixup.request()) {
        Err(CandidateHeadQualificationFailure::ProviderExit {
            run: QualificationRun::First,
            code: Some(code),
            stdout_bytes: 0,
            stderr,
        }) if code != 0
            && String::from_utf8_lossy(&stderr).contains("Unused buildscript fixups") => {}
        Err(other) => {
            return Err(format!(
                "unused buildscript decision returned the wrong typed refusal: {}",
                render_failure(other)
            ));
        }
        Ok(_) => return Err("unused buildscript decision was accepted".to_owned()),
    }
    Ok(Success::RealProviderFixture(
        "real provider fixture accepted deterministic published path-only input and refused an unused buildscript decision"
            .to_owned(),
    ))
}

fn required_path(name: &str) -> Result<PathBuf, String> {
    env::var_os(name)
        .map(PathBuf::from)
        .ok_or_else(|| format!("{name} is required"))
}

fn render_failure(failure: CandidateHeadQualificationFailure) -> String {
    let mut message = failure.to_string();
    let diagnostic = match &failure {
        CandidateHeadQualificationFailure::ProviderExit { stderr, .. }
        | CandidateHeadQualificationFailure::ProviderStderr { stderr, .. } => stderr.as_slice(),
        _ => &[],
    };
    if !diagnostic.is_empty() {
        message.push_str(": ");
        message.push_str(&String::from_utf8_lossy(diagnostic));
    }
    message
}

struct RealProviderFixture {
    root: PathBuf,
    provider: PathBuf,
    cargo: PathBuf,
    rustc: PathBuf,
    first_root: PathBuf,
    second_root: PathBuf,
    first_target: PathBuf,
    second_target: PathBuf,
}

impl RealProviderFixture {
    fn new(
        provider: PathBuf,
        cargo: PathBuf,
        rustc: PathBuf,
        unused_fixup: bool,
    ) -> Result<Self, String> {
        let nonce = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_err(|error| format!("system clock precedes Unix epoch: {error}"))?
            .as_nanos();
        let raw_root = env::temp_dir().join(format!(
            "reindeer-real-provider-qualification-{}-{nonce}",
            std::process::id()
        ));
        fs::create_dir(&raw_root)
            .map_err(|error| format!("could not create {}: {error}", raw_root.display()))?;
        let root = fs::canonicalize(&raw_root)
            .map_err(|error| format!("could not canonicalize {}: {error}", raw_root.display()))?;
        let first_root = root.join("candidate-one");
        let second_root = root.join("candidate-two");
        write_real_candidate(&first_root, unused_fixup)?;
        write_real_candidate(&second_root, unused_fixup)?;
        let targets = root.join("targets");
        create_dir_all(&targets)?;
        Ok(Self {
            root,
            provider,
            cargo,
            rustc,
            first_root,
            second_root,
            first_target: targets.join("run-one"),
            second_target: targets.join("run-two"),
        })
    }

    fn request(&self) -> CandidateHeadQualificationRequest {
        CandidateHeadQualificationRequest {
            provider_executable: self.provider.clone(),
            cargo_executable: self.cargo.clone(),
            rustc_executable: self.rustc.clone(),
            first_candidate_root: self.first_root.clone(),
            second_candidate_root: self.second_root.clone(),
            first_target_dir: self.first_target.clone(),
            second_target_dir: self.second_target.clone(),
        }
    }
}

impl Drop for RealProviderFixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

fn write_real_candidate(root: &Path, unused_fixup: bool) -> Result<(), String> {
    create_dir_all(&root.join("src"))?;
    create_dir_all(&root.join("third-party/qualification-leaf/src"))?;
    create_dir_all(&root.join("third-party/.cargo"))?;
    write(
        &root.join("Cargo.toml"),
        concat!(
            "[package]\n",
            "name = \"qualification-root\"\n",
            "version = \"0.1.0\"\n",
            "edition = \"2024\"\n",
            "\n[dependencies]\n",
            "qualification-leaf = { path = \"third-party/qualification-leaf\" }\n",
        )
        .as_bytes(),
    )?;
    write(&root.join("src/lib.rs"), b"pub fn root() {}\n")?;
    write(
        &root.join("third-party/qualification-leaf/Cargo.toml"),
        concat!(
            "[package]\n",
            "name = \"qualification-leaf\"\n",
            "version = \"0.1.0\"\n",
            "edition = \"2024\"\n",
        )
        .as_bytes(),
    )?;
    write(
        &root.join("third-party/qualification-leaf/src/lib.rs"),
        b"pub fn leaf() {}\n",
    )?;
    write(
        &root.join("Cargo.lock"),
        concat!(
            "# This file is automatically @generated by Cargo.\n",
            "# It is not intended for manual editing.\n",
            "version = 4\n",
            "\n[[package]]\n",
            "name = \"qualification-leaf\"\n",
            "version = \"0.1.0\"\n",
            "\n[[package]]\n",
            "name = \"qualification-root\"\n",
            "version = \"0.1.0\"\n",
            "dependencies = [\n",
            " \"qualification-leaf\",\n",
            "]\n",
        )
        .as_bytes(),
    )?;
    write(
        &root.join("reindeer.toml"),
        concat!(
            "manifest_path = \"Cargo.toml\"\n",
            "third_party_dir = \"third-party\"\n",
            "unresolved_fixup_error = true\n",
        )
        .as_bytes(),
    )?;
    write(&root.join("third-party/BUCK"), REAL_PROVIDER_EXPECTED_BUCK)?;
    write(&root.join("rust-toolchain.toml"), TOOLCHAIN_FILE)?;
    if unused_fixup {
        let fixup = root.join("third-party/fixups/qualification-leaf");
        create_dir_all(&fixup)?;
        write(&fixup.join("fixups.toml"), b"[buildscript]\nrun = true\n")?;
    }
    Ok(())
}

fn write(path: &Path, bytes: &[u8]) -> Result<(), String> {
    fs::write(path, bytes).map_err(|error| format!("could not write {}: {error}", path.display()))
}

fn create_dir_all(path: &Path) -> Result<(), String> {
    fs::create_dir_all(path)
        .map_err(|error| format!("could not create {}: {error}", path.display()))
}
